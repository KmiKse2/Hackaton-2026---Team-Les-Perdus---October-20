import 'dart:async';
import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:lifeflow/recommendations.dart';

Map<String, dynamic> snapshot(
        {int id = 1, bool blocked = false, int revision = 1}) =>
    {
      'customer': {'id': id},
      'customer_profile': {'blocked': blocked},
      'consent': {
        'effective_permissions': ['accounts', 'transactions'],
        'account_ids': ['scoped']
      },
      'signals': [revision],
    };

Map<String, dynamic> response({int id = 1, bool empty = false}) => {
      'customer_id': id,
      'recommendations': empty
          ? []
          : [
              {
                'id': 'rec_income',
                'title': 'Review your budget',
                'message':
                    'If your income has changed, a budget review could help.',
                'description':
                    'Review your regular expenses before changing your savings target.',
                'justification':
                    'Your recent payments suggest a possible income change.',
                'clarification_question': 'Has your income changed?',
                'requires_confirmation': true,
                'action_type': 'view_details',
                'action_label': 'View details',
                'display_priority': 2,
              },
            ],
    };

Widget screen(Map<String, dynamic> state,
        Future<Map<String, dynamic>> Function(int) load) =>
    MaterialApp(
        home: Scaffold(
            body: SingleChildScrollView(
      child: RecommendationSection(snapshot: state, load: load),
    )));

void main() {
  testWidgets('loads once through API; plain cards and safe local details',
      (tester) async {
    var requests = 0;
    final client = MockClient((request) async {
      requests++;
      expect(request.method, 'POST');
      expect(request.url.path, '/api/customers/1/ai-analysis');
      expect(request.headers['X-Demo-Token'], 'demo');
      expect(request.body, '');
      return http.Response(jsonEncode(response()), 200);
    });
    final api = RecommendationApi(client, 'http://localhost:8000', 'demo');
    await tester.pumpWidget(screen(snapshot(), api.analyze));
    await tester.pumpAndSettle();
    expect(find.text('Review your budget'), findsOneWidget);
    expect(find.text('Has your income changed?'), findsOneWidget);
    expect(find.textContaining('AI-generated by Gemini'), findsOneWidget);
    await tester.pumpWidget(screen(snapshot(), api.analyze));
    await tester.pumpAndSettle();
    expect(requests, 1);
    await tester.tap(find.text('View details'));
    await tester.pumpAndSettle();
    expect(find.textContaining('Review your regular expenses'), findsOneWidget);
    expect(requests, 1);
    expect(tester.takeException(), isNull);
    client.close();
  });

  testWidgets('loading, empty and explicit refresh', (tester) async {
    final pending = Completer<Map<String, dynamic>>();
    var requests = 0;
    Future<Map<String, dynamic>> load(int id) {
      requests++;
      return pending.future;
    }

    await tester.pumpWidget(screen(snapshot(), load));
    expect(find.text('Preparing your recommendations…'), findsOneWidget);
    pending.complete(response(empty: true));
    await tester.pumpAndSettle();
    expect(find.textContaining('No recommendations for now'), findsOneWidget);
    await tester.tap(find.text('Refresh recommendations'));
    await tester.pumpAndSettle();
    expect(requests, 2);
  });

  testWidgets(
      'blocked consent skips requests and invalidates in-flight response',
      (tester) async {
    final pending = Completer<Map<String, dynamic>>();
    var requests = 0;
    Future<Map<String, dynamic>> load(int id) {
      requests++;
      return pending.future;
    }

    await tester.pumpWidget(screen(snapshot(blocked: true), load));
    expect(requests, 0);
    await tester.pumpWidget(screen(snapshot(), load));
    await tester.tap(find.text('Refresh recommendations'));
    await tester.pump();
    expect(requests, 1);
    await tester.pumpWidget(screen(snapshot(blocked: true), load));
    pending.complete(response());
    await tester.pumpAndSettle();
    expect(find.text('Review your budget'), findsNothing);
    expect(find.textContaining('Recommendations are paused'), findsOneWidget);
  });

  testWidgets('context changes invalidate without automatic poll requests',
      (tester) async {
    var requests = 0;
    Future<Map<String, dynamic>> load(int id) async {
      requests++;
      return response(id: id);
    }

    await tester.pumpWidget(screen(snapshot(), load));
    await tester.pumpAndSettle();
    await tester.pumpWidget(screen(snapshot(revision: 2), load));
    await tester.pumpAndSettle();
    expect(find.text('Review your budget'), findsNothing);
    expect(find.textContaining('Your situation has changed'), findsOneWidget);
    expect(requests, 1);
  });

  testWidgets('switching customers discards old response', (tester) async {
    final old = Completer<Map<String, dynamic>>();
    Future<Map<String, dynamic>> load(int id) =>
        id == 1 ? old.future : Future.value(response(id: id, empty: true));
    await tester.pumpWidget(screen(snapshot(), load));
    await tester.pumpWidget(screen(snapshot(id: 2), load));
    await tester.pumpAndSettle();
    old.complete(response());
    await tester.pumpAndSettle();
    expect(find.text('Review your budget'), findsNothing);
    expect(find.textContaining('No recommendations for now'), findsOneWidget);
  });

  testWidgets('provider failure is friendly and retry is explicit',
      (tester) async {
    var requests = 0;
    final client = MockClient((request) async {
      requests++;
      return requests == 1
          ? http.Response('private provider error', 503)
          : http.Response(jsonEncode(response()), 200);
    });
    final api = RecommendationApi(client, 'http://localhost', '');
    await tester.pumpWidget(screen(snapshot(), api.analyze));
    await tester.pumpAndSettle();
    expect(find.textContaining('temporarily unavailable'), findsOneWidget);
    expect(find.textContaining('private provider error'), findsNothing);
    await tester.tap(find.text('Retry recommendations'));
    await tester.pumpAndSettle();
    expect(find.text('Review your budget'), findsOneWidget);
    expect(requests, 2);
    client.close();
  });

  testWidgets('cards fit narrow screens and reject arbitrary actions',
      (tester) async {
    tester.view.physicalSize = const Size(320, 800);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    await tester.pumpWidget(screen(snapshot(), (_) async => response()));
    await tester.pumpAndSettle();
    expect(tester.takeException(), isNull);
    final invalid = response(id: 2);
    invalid['recommendations'][0]['action_type'] = 'open_url';
    await tester.pumpWidget(screen(snapshot(id: 2), (_) async => invalid));
    await tester.pumpAndSettle();
    expect(find.text('View details'), findsNothing);
    expect(find.textContaining('response was invalid'), findsOneWidget);
  });

  test('API rejects cross-customer and malformed payloads; maps consent error',
      () async {
    for (final value in [
      response(id: 2),
      {'customer_id': 1}
    ]) {
      final client =
          MockClient((_) async => http.Response(jsonEncode(value), 200));
      await expectLater(
          RecommendationApi(client, 'http://localhost', '').analyze(1),
          throwsA(isA<RecommendationFailure>()));
      client.close();
    }
    final client = MockClient((_) async => http.Response('private', 403));
    await expectLater(
        RecommendationApi(client, 'http://localhost', '').analyze(1),
        throwsA(isA<RecommendationFailure>()
            .having((e) => e.message, 'message', contains('permissions'))));
    client.close();
  });
}
